"""Extract SJTU recall papers into a browser-friendly JavaScript question bank."""

from __future__ import annotations

import json
import re
from pathlib import Path

import pdfplumber
from pypdf import PdfReader


ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "sources"
OUTPUT = ROOT / "quiz-app" / "archive-questions.js"

PAPERS = {
    "2023": (SOURCES / "23分流考回忆.pdf", "pypdf"),
    "2024": (SOURCES / "24分流考回忆题.pdf", "pdfplumber"),
    "2026": (SOURCES / "26分流考回忆题.pdf", "pdfplumber"),
}


def extract(path: Path, engine: str) -> str:
    if engine == "pypdf":
        text = "\n".join(page.extract_text() or "" for page in PdfReader(path).pages)
    else:
        with pdfplumber.open(path) as pdf:
            pages = []
            for page in pdf.pages:
                # The diagonal watermark uses 63pt glyphs; normal content is <=22pt.
                clean_page = page.filter(
                    lambda obj: obj.get("object_type") != "char"
                    or obj.get("size", 0) < 30
                )
                pages.append(clean_page.extract_text(x_tolerance=2, y_tolerance=3) or "")
            text = "\n".join(pages)
    return normalize(text)


def normalize(text: str) -> str:
    text = "".join(char if char in "\n\t" or ord(char) >= 32 else " " for char in text)
    text = text.replace("仅供学习使用，严禁商用", "")
    text = re.sub(r"试题第\s*\d+\s*页（共\s*\d+\s*页）", "", text)
    text = re.sub(r"\.{4,}", " ", text)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def sections(year: str, text: str) -> list[tuple[str, str]]:
    if year == "2023":
        math, logic = re.split(r"第二部分\s*逻辑题", text, maxsplit=1)
        math = re.split(r"第一部分\s*数学题", math, maxsplit=1)[-1]
        return [("数学", math), ("逻辑", logic)]

    math_match = re.search(r"一、数学部分[^\n]*", text)
    logic_match = re.search(r"二、逻辑部分[^\n]*", text)
    if not math_match or not logic_match:
        raise ValueError(f"Cannot find section headings in {year}")
    return [
        ("数学", text[math_match.end() : logic_match.start()]),
        ("逻辑", text[logic_match.end() :]),
    ]


def split_questions(text: str) -> list[tuple[int, str]]:
    starts = list(re.finditer(r"(?m)^\s*(\d{1,3})\.\s*", text))
    questions = []
    for index, start in enumerate(starts):
        end = starts[index + 1].start() if index + 1 < len(starts) else len(text)
        number = int(start.group(1))
        block = text[start.end() : end].strip()
        if block:
            questions.append((number, block))
    return questions


def split_options(block: str) -> tuple[str, list[str]]:
    markers = list(re.finditer(r"(?<![A-Za-z])([A-E])[\.．]\s*", block))
    if len(markers) < 2:
        return tidy(block), []

    stem = tidy(block[: markers[0].start()])
    options = []
    for index, marker in enumerate(markers):
        end = markers[index + 1].start() if index + 1 < len(markers) else len(block)
        option = tidy(block[marker.end() : end])
        options.append(option or f"{marker.group(1)}（请参照原卷排版）")
    return stem, options


def tidy(value: str) -> str:
    value = re.sub(r"\s*\n\s*", " ", value)
    return re.sub(r"\s{2,}", " ", value).strip(" ，")


def build() -> list[dict[str, object]]:
    result = []
    for year, (path, engine) in PAPERS.items():
        text = extract(path, engine)
        for subject, section in sections(year, text):
            for number, block in split_questions(section):
                stem, options = split_options(block)
                if not options:
                    options = ["本题为回忆题，请参照原卷作答"]
                result.append(
                    {
                        "id": f"{year}-{subject}-{number}",
                        "number": number,
                        "year": year,
                        "subject": subject,
                        "topic": "历年回忆题",
                        "correct": -1,
                        "stem": stem,
                        "options": options,
                        "explanation": "原回忆卷未提供可核验答案，本题暂不计入正确率。",
                        "note": f"来源：上海交通大学 {year} 年平台预分专业能力测试回忆卷；题面以原 PDF 为准。",
                        "kind": "archive",
                        "sourceFile": f"../sources/{path.name}",
                    }
                )
    return result


def main() -> None:
    questions = build()
    payload = json.dumps(questions, ensure_ascii=False, indent=2)
    OUTPUT.write_text(
        "// Generated by scripts/import_recall_pdfs.py.\n"
        f"const ARCHIVE_QUESTIONS = {payload};\n",
        encoding="utf-8",
    )
    counts: dict[str, int] = {}
    for question in questions:
        year = str(question["year"])
        counts[year] = counts.get(year, 0) + 1
    print(f"Wrote {len(questions)} questions to {OUTPUT}")
    print("Counts:", counts)


if __name__ == "__main__":
    main()
